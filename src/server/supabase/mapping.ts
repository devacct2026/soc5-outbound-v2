// Row <-> domain mapping for the `requests` table.
import type { RequestRecord } from "../../domain/requests/lifecycle.ts";

type Row = Record<string, unknown>;
const s = (v: unknown) => (v === null || v === undefined ? null : String(v));

export function fromRow(r: Row): RequestRecord {
  return {
    id: String(r.id),
    requestTimestamp: String(r.request_timestamp),
    submittedAt: String(r.submitted_at),
    clusterId: s(r.cluster_id),
    cluster: String(r.cluster),
    region: String(r.region),
    dockNo: String(r.dock_no),
    backlogs: Number(r.backlogs),
    backlogsTimestamp: s(r.backlogs_timestamp),
    truckSize: r.truck_size as RequestRecord["truckSize"],
    truckType: r.truck_type as RequestRecord["truckType"],
    createdBy: String(r.created_by),
    creatorRole: r.creator_role as RequestRecord["creatorRole"],
    status: r.status as RequestRecord["status"],
    approvalStatus: r.approval_status as RequestRecord["approvalStatus"],
    approvalVersion: Number(r.approval_version),
    approvalCorrelationId: String(r.approval_correlation_id),
    approvalSource: (r.approval_source as RequestRecord["approvalSource"]) ?? null,
    approvedAt: s(r.approved_at),
    approvedBy: s(r.approved_by),
    rejectionDisposition: (r.rejection_disposition as RequestRecord["rejectionDisposition"]) ?? null,
    rejectionReturnRole: (r.rejection_return_role as RequestRecord["rejectionReturnRole"]) ?? null,
    rejectionRemarks: s(r.rejection_remarks),
    rejectedAt: s(r.rejected_at),
    rejectedBy: s(r.rejected_by),
    cancellationRemarks: s(r.cancellation_remarks),
    cancelledAt: s(r.cancelled_at),
    cancelledBy: s(r.cancelled_by),
    plateNumber: s(r.plate_number),
    provideTime: s(r.provide_time),
    truckAssignedBy: s(r.truck_assigned_by),
    driverId: s(r.driver_id),
    driverAssignedAt: s(r.driver_assigned_at),
    driverAssignedBy: s(r.driver_assigned_by),
    linehaulTripNo: s(r.linehaul_trip_no),
    linehaulTripAt: s(r.linehaul_trip_at),
    dockedAt: s(r.docked_at),
    legacyStatus: s(r.legacy_status),
    legacyReview: (r.legacy_review as RequestRecord["legacyReview"]) ?? null,
    rowVersion: Number(r.row_version),
    createdAt: String(r.created_at),
  };
}

